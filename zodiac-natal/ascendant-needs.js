  function assertIsString(value, paramName) {
    if (typeof value !== 'string') {
      throw new TypeError(`${paramName} 必須是字串，實際收到：${value === null ? 'null' : typeof value}`);
    }
  }

  /* 模組載入時的資料完整性自我檢查，規則對照 ascendant-needs-writing-guideline.md，
     跟 moon-needs.js 的檢查邏輯對稱（兩份表用同一套結構規則，只是內容各自獨立）。 */
  function validateAscendantNeedsData() {
    Object.entries(ASCENDANT_NEEDS).forEach(([sign, entry]) => {
      if (!SIGN_ORDER.includes(sign)) {
        throw new Error(`資料錯誤：ASCENDANT_NEEDS 的鍵「${sign}」不是合法的正式星座名稱`);
      }
      if (entry.coreNeeds.length !== 2) {
        throw new Error(`資料錯誤：「${sign}」的 coreNeeds 必須恰好 2 個，實際 ${entry.coreNeeds.length} 個`);
      }
      if (entry.secondaryNeeds.length !== 2) {
        throw new Error(`資料錯誤：「${sign}」的 secondaryNeeds 必須恰好 2 個，實際 ${entry.secondaryNeeds.length} 個`);
      }
      const allTags = [...entry.coreNeeds, ...entry.secondaryNeeds];
      allTags.forEach(tag => {
        if (!(tag in TAG_VOCABULARY)) {
          throw new Error(`資料錯誤：「${sign}」使用了未定義在 TAG_VOCABULARY 裡的標籤「${tag}」`);
        }
      });
      const overlap = entry.coreNeeds.filter(t => entry.secondaryNeeds.includes(t));
      if (overlap.length > 0) {
        throw new Error(`資料錯誤：「${sign}」的 coreNeeds 跟 secondaryNeeds 有重複標籤：${overlap.join('、')}`);
      }
      const rationaleKeys = Object.keys(entry.rationale || {});
      const missingRationale = allTags.filter(t => !rationaleKeys.includes(t));
      if (missingRationale.length > 0) {
        throw new Error(`資料錯誤：「${sign}」缺少標籤「${missingRationale.join('、')}」的 rationale 說明`);
      }
      const extraRationale = rationaleKeys.filter(k => !allTags.includes(k));
      if (extraRationale.length > 0) {
        throw new Error(`資料錯誤：「${sign}」的 rationale 包含未使用到的標籤鍵「${extraRationale.join('、')}」`);
      }
    });
  }
  validateAscendantNeedsData();

  function deepFreeze(obj) {
    Object.values(obj).forEach(v => {
      if (v && typeof v === 'object' && !Object.isFrozen(v)) deepFreeze(v);
    });
    return Object.freeze(obj);
  }
  deepFreeze(ASCENDANT_NEEDS);

  function getAscendantNeedsByName(signName) {
    assertIsString(signName, 'signName');
    const entry = ASCENDANT_NEEDS[signName];
    if (!entry) return undefined;
    return {
      coreNeeds: entry.coreNeeds.slice(),
      secondaryNeeds: entry.secondaryNeeds.slice(),
      rationale: { ...entry.rationale },
      tagSchemaVersion: TAG_SCHEMA_VERSION
    };
  }

